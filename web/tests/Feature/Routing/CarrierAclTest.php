<?php

namespace Tests\Feature\Routing;

use App\Services\FirewallSync;
use App\Services\Freeswitch\CarrierAcl;
use App\Services\Freeswitch\EventSocket;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class CarrierAclTest extends TestCase
{
    use RefreshDatabase;

    public function test_the_acl_lists_carriers_but_not_the_switch_itself(): void
    {
        config(['softswitch.public_ip' => '147.182.148.63']);
        $esl = $this->mock(EventSocket::class);
        $esl->shouldReceive('api')->with('reloadacl')->once()->andReturn('+OK');
        $dir = sys_get_temp_dir().'/acl-'.uniqid();
        mkdir($dir);
        $acl = new CarrierAcl($esl, new FirewallSync(fn () => []), $dir);

        $this->assertSame(['10.1.2.0/24', '142.93.156.188/32', '2001:db8::5/128'],
            $acl->nets(['142.93.156.188', '147.182.148.63', '127.0.0.1', '10.1.2.0/24', '2001:db8::5', 'junk', '0.0.0.0/0']));
        $this->assertSame("<include>\n  <!-- Generated by the Softswitch app from the carrier allowlist. Do not edit. -->\n  <node type=\"allow\" cidr=\"142.93.156.188/32\"/>\n</include>\n",
            $acl->render(['142.93.156.188/32']));

        $this->assertSame(['count' => 0, 'reloaded' => true], $acl->sync());   // written once...
        $this->assertSame(['count' => 0, 'reloaded' => false], $acl->sync());  // ...and left alone when unchanged
        $this->assertFileExists("{$dir}/carriers.xml");
        array_map('unlink', glob("{$dir}/*"));
        rmdir($dir);
    }
}
