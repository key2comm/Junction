<?php

namespace App\Models;

use App\Enums\Transport;
use App\Jobs\SyncSwitchConfig;
use Database\Factories\GatewayFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * A carrier's SIP trunk (shown as "SIP trunks" on the carrier page). `label`
 * says what it's for; `name` is the FreeSWITCH gateway name (generated).
 * The password is encrypted with the app key, so FreeSWITCH config for
 * gateways is generated by Laravel rather than read from the table.
 */
#[Hidden(['password'])]
#[Fillable(['trunk_id', 'name', 'label', 'from_user', 'from_domain', 'outbound_proxy', 'send_rpid', 'send_pai', 'host', 'port', 'transport', 'username', 'password', 'register', 'enabled', 'priority', 'weight'])]
class Gateway extends Model
{
    /** @use HasFactory<GatewayFactory> */
    use HasFactory;

    protected function casts(): array
    {
        return [
            'port' => 'integer',
            'transport' => Transport::class,
            'password' => 'encrypted',
            'register' => 'boolean',
            'send_rpid' => 'boolean',
            'send_pai' => 'boolean',
            'enabled' => 'boolean',
            'priority' => 'integer',
            'weight' => 'integer',
        ];
    }

    public function trunk(): BelongsTo
    {
        return $this->belongsTo(Trunk::class);
    }

    protected static function booted(): void
    {
        // Gateways and the firewall allowlist follow the database.
        static::saved(fn () => SyncSwitchConfig::soon());
        static::deleted(fn () => SyncSwitchConfig::soon());
    }
}
