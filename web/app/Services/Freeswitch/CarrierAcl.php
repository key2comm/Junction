<?php

namespace App\Services\Freeswitch;

use App\Services\FirewallSync;
use App\Support\IpNet;
use Illuminate\Support\Facades\File;
use RuntimeException;

/**
 * FreeSWITCH's "carriers" access list (acl/carriers.xml, included by
 * acl.conf.xml): the carrier allowlist (FirewallSync::allowlist(), the same
 * addresses the firewall lets reach the carrier port). Carriers that send to
 * the PBX port (5060) instead of the carrier port are let in without digest
 * auth (internal profile apply-inbound-acl) and routed like carrier traffic.
 * The switch's own IP is left out: its PBX phones (and the self-test) must
 * still authenticate.
 */
class CarrierAcl
{
    public const FILE = 'carriers.xml';

    public function __construct(private EventSocket $esl, private FirewallSync $firewall, private string $directory) {}

    /** @return array{count: int, reloaded: bool} */
    public function sync(): array
    {
        if (! is_dir($this->directory) || ! is_writable($this->directory)) {
            throw new RuntimeException("ACL directory {$this->directory} is missing or not writable.");
        }
        $nets = $this->nets($this->firewall->allowlist());
        $xml = $this->render($nets);
        $path = "{$this->directory}/".self::FILE;
        if (is_file($path) && file_get_contents($path) === $xml) {
            return ['count' => count($nets), 'reloaded' => false];
        }
        File::put("{$path}.tmp", $xml);
        chmod("{$path}.tmp", 0640);
        rename("{$path}.tmp", $path);
        $this->esl->api('reloadacl');

        return ['count' => count($nets), 'reloaded' => true];
    }

    /** @param  list<string>  $entries  @return list<string> CIDRs */
    public function nets(array $entries): array
    {
        $own = array_filter([config('softswitch.public_ip'), '127.0.0.1', '::1']);
        $nets = [];
        foreach ($entries as $entry) {
            $net = IpNet::normalize((string) $entry);
            if ($net === null || IpNet::tooBroad($net) || in_array($net, $own, true)) {
                continue;
            }
            $nets[] = str_contains($net, '/') ? $net : $net.(IpNet::version($net) === 6 ? '/128' : '/32');
        }
        $nets = array_values(array_unique($nets));
        sort($nets);

        return $nets;
    }

    /** @param  list<string>  $nets */
    public function render(array $nets): string
    {
        $lines = array_map(fn ($n) => '  <node type="allow" cidr="'.htmlspecialchars($n, ENT_XML1 | ENT_QUOTES).'"/>', $nets);

        return "<include>\n  <!-- Generated by the Softswitch app from the carrier allowlist. Do not edit. -->\n"
            .implode("\n", $lines).($lines ? "\n" : '')."</include>\n";
    }
}
